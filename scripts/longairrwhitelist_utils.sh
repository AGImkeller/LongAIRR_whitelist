#------------------------------tool helpers-------------------------------------

print_tool_version() {
    local tool="$1"

    case "${tool}" in
        samtools)
            "${tool}" --version 2>/dev/null | head -n 1 || true
            ;;
        fastcat|percula|spaceranger)
            "${tool}" --version 2>/dev/null || "${tool}" --help 2>&1 | head -n 1 || true
            ;;
        *)
            "${tool}" --version 2>/dev/null | head -n 1 || true
            ;;
    esac
}

print_array_command() {
    printf ' %q' "$@"
    echo
}

#------------------------------input detection----------------------------------

is_fastq_name() {
    local path="$1"
    case "${path,,}" in
        *.fastq|*.fq|*.fastq.gz|*.fq.gz|*.fastq.bgz|*.fq.bgz) return 0 ;;
        *) return 1 ;;
    esac
}

is_bam_name() {
    local path="$1"
    case "${path,,}" in
        *.bam) return 0 ;;
        *) return 1 ;;
    esac
}

count_fastq_in_dir() {
    local path="$1"
    find "${path}" -type f \( \
        -name '*.fastq' -o -name '*.fq' -o \
        -name '*.fastq.gz' -o -name '*.fq.gz' -o \
        -name '*.fastq.bgz' -o -name '*.fq.bgz' \
    \) | head -n 2 | wc -l
}

count_bam_in_dir() {
    local path="$1"
    find "${path}" -type f -name '*.bam' | head -n 2 | wc -l
}

detect_input_type() {
    local input="$1"
    local requested="$2"

    if [[ "${requested}" != "auto" ]]; then
        echo "${requested}"
        return 0
    fi

    if [[ -f "${input}" ]]; then
        if is_bam_name "${input}"; then
            echo "bam"
            return 0
        fi
        if is_fastq_name "${input}"; then
            echo "fastq"
            return 0
        fi

        echo "[ERROR] Could not auto-detect input type from file extension: ${input}" >&2
        echo "        Use --input-type bam or --input-type fastq." >&2
        return 1
    fi

    if [[ -d "${input}" ]]; then
        local n_bam n_fastq
        n_bam="$(count_bam_in_dir "${input}" | tr -d ' ')"
        n_fastq="$(count_fastq_in_dir "${input}" | tr -d ' ')"

        if [[ "${n_bam}" -gt 0 && "${n_fastq}" -gt 0 ]]; then
            echo "[ERROR] Directory contains both BAM and FASTQ-like files: ${input}" >&2
            echo "        Use --input-type bam or --input-type fastq to choose explicitly." >&2
            return 1
        fi
        if [[ "${n_bam}" -gt 0 ]]; then
            echo "bam"
            return 0
        fi
        if [[ "${n_fastq}" -gt 0 ]]; then
            echo "fastq"
            return 0
        fi

        echo "[ERROR] Could not auto-detect BAM or FASTQ files in directory: ${input}" >&2
        echo "        Use --input-type bam or --input-type fastq if this is intentional." >&2
        return 1
    fi

    echo "[ERROR] Input is neither file nor directory: ${input}" >&2
    return 1
}

#--------------------------Space Ranger template--------------------------------

write_spaceranger_template() {
    local template_path="$1"
    local sample="$2"
    local fastqs_path="$3"

    cat > "${template_path}" <<EOF_TEMPLATE
#!/usr/bin/env bash
set -euo pipefail

# Space Ranger template generated by LongAIRR_whitelist.
# Edit all placeholders before running.
# Keep --create-bam=true; LongAIRR_whitelist build-index uses:
#   outs/possorted_genome_bam.bam

spaceranger count \\
  --id=${sample}_spaceranger \\
  --transcriptome=<path_to_spaceranger_reference> \\
  --fastqs=${fastqs_path} \\
  --sample=<sample_name_if_required> \\
  --slide=<visium_hd_slide_serial> \\
  --area=<capture_area> \\
  --cytaimage=<path_to_cytassist_image_tiff> \\
  --localcores=8 \\
  --localmem=12 \\
  --create-bam=true
EOF_TEMPLATE

    chmod +x "${template_path}"
}

#-----------------------------preprocess output metadata------------------------

write_manifest() {
    local manifest_path="$1"
    local platform="$2"
    local input="$3"
    local input_type="$4"
    local out="$5"
    local sample="$6"
    local command_string="$7"
    local template_path="$8"

    cat > "${manifest_path}" <<EOF_MANIFEST
{
  "tool": "LongAIRR_whitelist",
  "tool_version": "${VERSION}",
  "step": "preprocess",
  "platform": "${platform}",
  "input": "${input}",
  "input_type": "${input_type}",
  "out": "${out}",
  "sample": "${sample}",
  "command": "${command_string}",
  "spaceranger_template": "${template_path}",
  "next_step": "Run Space Ranger with --create-bam=true, then run longairrwhitelist build-index on outs/possorted_genome_bam.bam"
}
EOF_MANIFEST
}
